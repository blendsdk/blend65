/** Generated byte storage remains separate from the source counter's word type. */
const COUNTER_BYTE = Object.freeze({ kind: "scalar" as const, name: "byte" as const });

/**
 * Build only the finite source-associated emission schedule for one ordinary context.
 * Original source positions and value IDs remain the storage authority; generated
 * labels distinguish occurrences, not source variables or function invocations.
 * @param blocks Original emitted source blocks selected by the execution-context owner.
 * @param input Existing lowering context and optional finite loop policy.
 * @param owner Exact source function binding, never a display-name match.
 * @param domain Actual execution domain; interrupt contexts retain ordinary loops.
 * @returns Original CFG facts plus a bounded occurrence schedule, with no emitted storage.
 */
export function prepareFixedLoops(
  blocks: readonly SemanticBlock[],
  input: MachineLoweringInput,
  owner: BindingId,
  domain: ExecutionDomain,
): FixedLoopRuntime {
  const blockIndexes = new Map(blocks.map((block, index) => [block.id, index] as const));
  const predecessors = new Map(blocks.map((block) => [block.id, [] as string[]] as const));
  for (const block of blocks)
    for (const target of semanticSuccessors(block.terminator))
      predecessors.get(target)?.push(block.id);
  const positions = Object.freeze(
    blocks.flatMap((block) =>
      Array.from({ length: block.operations.length + 1 }, (_, operation) =>
        Object.freeze({ block: block.id, operation }),
      ),
    ),
  );
  const policy = input.sourceFacts?.loopPolicy;
  if (
    policy !== undefined &&
    ![
      "original",
      "low-byte",
      "x-first",
      "y-first",
      "flat-eight-x-first",
      "flat-eight-y-first",
      "mixed",
    ].includes(policy)
  )
    throw loweringFailure("Unknown fixed-loop construction policy", owner.span);
  const fn =
    policy === undefined || policy === "original"
      ? undefined
      : input.program.semantic.functions.find(
          (candidate) => bindingIdentityKey(candidate.id) === bindingIdentityKey(owner),
        );
  const facts = fn === undefined ? [] : (input.sourceFacts?.functions.get(fn)?.loops ?? []);
  if (facts.some((loop) => !validFixedLoopFacts(loop)))
    throw loweringFailure("Flat-eight facts do not match the checked source template", owner.span);
  const occurrences = new Map<string, FixedLoopOccurrence>(
    blocks.map((source) => [source.id, { source, loop: null, iteration: null }]),
  );
  const expanded = new Map<FixedLoopFacts, ReadonlySet<string>>();
  const ordinalValues = new Map<FixedLoopFacts, ReadonlySet<string>>();
  const omitted = new Set<SemanticOperation>();
  const removed = new Set<SemanticBlock>();
  const bodies = new Map<SemanticBlock, readonly SemanticBlock[]>();
  const redirected = new Map<SemanticBlock, string>();
  if (domain === "main" && fn?.entryKind !== "interrupt" && policy?.startsWith("flat-eight-")) {
    for (const loop of facts) {
      if (
        !loop.flatEight ||
        loop.exactIterations !== 8 ||
        loop.initial.kind !== "constant" ||
        loop.initial.value !== 0 ||
        loop.parameter ||
        loop.outsideAccesses.length > 0 ||
        loop.members.size !== 2 ||
        ![loop.preheader, loop.header, loop.body, loop.update, loop.exit].every((block) =>
          blocks.includes(block),
        )
      )
        continue;
      const values = new Set(
        loop.body.operations.flatMap((operation) =>
          "result" in operation && operation.result !== null ? [operation.result] : [],
        ),
      );
      if (!bodyValuesStayLocal(loop, values)) continue;
      const ordinals = new Set<string>();
      for (const operation of loop.body.operations) {
        if (!("result" in operation) || operation.result === null) continue;
        if (
          (operation.kind === "load" &&
            operation.place.path.length === 0 &&
            bindingIdentityKey(operation.place.root) === bindingIdentityKey(loop.counter)) ||
          ((operation.kind === "unary" ||
            operation.kind === "binary" ||
            operation.kind === "convert") &&
            potentialValueInputs(operation).some((value) => ordinals.has(value)))
        )
          ordinals.add(operation.result);
      }
      if (!derivedIndicesAreInBounds(loop, ordinals)) continue;
      const copies = Array.from({ length: 8 }, (_, iteration) => {
        const id = `${loop.body.id}.iteration.${iteration}`;
        occurrences.set(id, Object.freeze({ source: loop.body, loop, iteration }));
        const terminator: SemanticTerminator = Object.freeze({
          kind: "jump",
          target: iteration === 7 ? loop.exit.id : `${loop.body.id}.iteration.${iteration + 1}`,
        });
        return Object.freeze({ ...loop.body, id, terminator });
      });
      bodies.set(loop.body, Object.freeze(copies));
      redirected.set(loop.preheader, copies[0]!.id);
      removed.add(loop.header);
      removed.add(loop.update);
      omitted.add(loop.initialization);
      expanded.set(loop, values);
      ordinalValues.set(loop, ordinals);
    }
  }
  const scheduled = blocks.flatMap((block) => {
    if (removed.has(block)) return [];
    const copies = bodies.get(block);
    if (copies !== undefined) return copies;
    const target = redirected.get(block);
    return [
      target === undefined
        ? block
        : Object.freeze({ ...block, terminator: Object.freeze({ kind: "jump" as const, target }) }),
    ];
  });
  const counterFacts = Object.freeze(
    policy !== undefined &&
      policy !== "original" &&
      domain === "main" &&
      fn?.entryKind !== "interrupt"
      ? facts.filter(
          (loop) =>
            !expanded.has(loop) &&
            !loop.parameter &&
            loop.outsideAccesses.length === 0 &&
            loop.bound <= 8 &&
            loop.initial.domain.maximum <= 8 &&
            [loop.preheader, loop.header, loop.body, loop.update, loop.exit].every((block) =>
              blocks.includes(block),
            ) &&
            [...loop.members].every((id) => blockIndexes.has(id)),
        )
      : [],
  );
  const consumers = new Map<string, (SemanticOperation | null)[]>();
  if (counterFacts.length > 0)
    for (const block of blocks) {
      for (const operation of block.operations)
        for (const value of potentialValueInputs(operation)) {
          const uses = consumers.get(value) ?? [];
          uses.push(operation);
          consumers.set(value, uses);
        }
      const edge = block.terminator;
      const value =
        edge.kind === "branch" ? edge.condition : edge.kind === "return" ? edge.value : null;
      if (value !== null) consumers.set(value, [...(consumers.get(value) ?? []), null]);
    }
  return {
    observerEvidence: input.observerEvidence === true,
    cpu: input.profile.cpu,
    counterFacts,
    registers: new Map(),
    indexViews: new Map(),
    consumedIndices: new Set(),
    consumers,
    stageIds: new Set(counterFacts.length === 0 ? [] : declaredStorageIds(input)),
    counterOperations: new Map(),
    counters: new Map(),
    sourceBlocks: new Map(),
    blockIndexes,
    predecessors,
    positions,
    blocks: Object.freeze(scheduled),
    occurrences,
    omitted,
    expanded,
    ordinalValues,
    policy,
    current: undefined,
    emitted: new Map(),
  };
}

/**
 * Declare selected counter recipes before binding; reference word homes remain pending closure.
 * @param state Current source, representation and finite request context.
 * @param ordinalBounds Existing per-operation proofs also consumed by shift lowering.
 */
export function prepareFixedCounterStorage(
  state: FunctionLoweringState,
  ordinalBounds: ReadonlyMap<SemanticOperation, ReadonlyMap<string, bigint>>,
): void {
  const runtime = state.fixedLoops;
  if (runtime === undefined) return;
  for (const [loop, register] of selectFixedCounterRegisters(state, ordinalBounds))
    runtime.registers.set(loop, register);
  for (const loop of runtime.counterFacts) {
    const register = runtime.registers.get(loop) ?? null;
    if (runtime.policy !== "low-byte" && runtime.policy !== "mixed" && register === null) continue;
    const original = loweredPlace(loop.initialization.place, 2, false, state);
    if (original.kind !== "storage")
      throw loweringFailure("Fixed counter has no source function home", loop.initialization.span);
    const request =
      register === null
        ? requestStorage(
            state,
            `fixed-counter:${bindingIdentityKey(loop.counter)}`,
            "temporary",
            1,
            state.input.preferZeroPage === true &&
              bindingIdentityKey(state.owner) !==
                bindingIdentityKey(state.input.program.semantic.main)
              ? "zero-page-preferred"
              : "ram",
            loop.initialization.span,
            "Byte representation of one proved private word counter",
            COUNTER_BYTE,
          )
        : null;
    const selected: FixedCounterRuntime = {
      loop,
      originalRequestId: original.requestId,
      home:
        request === null
          ? null
          : Object.freeze({ kind: "storage", requestId: request.id, bytes: 1, signed: false }),
      register,
      parentInitialization: null,
      ownWrites: new Set(),
      reads: new Map(),
    };
    const counter = prepareParentCounterInitialization(selected, state);
    runtime.counters.set(bindingIdentityKey(loop.counter), counter);
    for (const operation of [
      ...loop.header.operations,
      ...loop.update.operations,
      loop.initialization,
    ])
      runtime.counterOperations.set(operation, counter);
  }
}

/**
 * Consume only identified counter control/read operations; all other operations stay ordinary.
 * Word reads remain zero-extended and existing argument-stage homes keep both bytes.
 * @param operation Original source operation, not a source-name or label pattern.
 * @param state Current finite counter recipe and ordinary lowering values.
 * @returns A selected sequence, or null when the existing dispatcher must own the operation.
 */
export function lowerFixedCounterOperation(
  operation: SemanticOperation,
  state: FunctionLoweringState,
  index = 0,
): readonly MachineInstruction[] | null {
  const selected = state.fixedLoops?.counterOperations.get(operation);
  if (selected !== undefined) {
    const { loop, home, register } = selected;
    if (operation === loop.initialization) {
      const parentInitialization = lowerParentCounterInitialization(selected, state);
      if (parentInitialization !== null) return parentInitialization;
      const value = state.values.get(loop.initialization.value);
      if (value === undefined || value.kind === "condition")
        throw loweringFailure("Fixed counter initializer has no retained value", operation.span);
      const instructions: MachineInstruction[] = [];
      if (register === null) {
        if (home === null)
          throw loweringFailure("Byte counter has no declared home", operation.span);
        appendLoadA(instructions, value, 0, state, operation.span);
        instructions.push(storeA(home, 0, state, operation.span));
      } else {
        const low = value.kind === "zero-extended" ? value.low : value;
        if (low.kind === "register") {
          appendLoadA(instructions, value, 0, state, operation.span);
          instructions.push(
            machineInstruction(
              state.input.profile.cpu,
              register === "x" ? "tax" : "tay",
              "implied",
              null,
              [],
              operation.span,
            ),
          );
        } else
          instructions.push(
            machineInstruction(
              state.input.profile.cpu,
              register === "x" ? "ldx" : "ldy",
              modeForValue(value),
              operandForValue(value),
              [],
              operation.span,
            ),
          );
        selected.ownWrites.add(instructions.at(-1)!);
      }
      // Other source operations can observe the final high-byte load of the
      // original word store before the first comparison replaces its flags.
      if (
        loop.preheader.operations.at(-1) !== loop.initialization &&
        (register !== null || !(loop.initial.kind === "constant" && loop.initial.value === 0))
      )
        instructions.push(
          machineInstruction(
            state.input.profile.cpu,
            "lda",
            "immediate",
            { kind: "immediate", value: 0 },
            [],
            operation.span,
          ),
        );
      return Object.freeze(instructions);
    }
    if (operation === loop.comparison) {
      const instructions: MachineInstruction[] = [];
      if (register === null) {
        if (home === null)
          throw loweringFailure("Byte counter has no declared home", operation.span);
        appendLoadA(instructions, home, 0, state, operation.span);
      }
      instructions.push(
        machineInstruction(
          state.input.profile.cpu,
          register === "x" ? "cpx" : register === "y" ? "cpy" : "cmp",
          "immediate",
          { kind: "immediate", value: loop.bound },
          [],
          operation.span,
        ),
        machineInstruction(
          state.input.profile.cpu,
          "lda",
          "immediate",
          { kind: "immediate", value: 0 },
          [],
          operation.span,
        ),
        machineInstruction(
          state.input.profile.cpu,
          "sbc",
          "immediate",
          { kind: "immediate", value: 0 },
          [],
          operation.span,
        ),
      );
      state.values.set(
        loop.comparison.result,
        Object.freeze({ kind: "condition", whenTrue: "bcc", usesFlag: "c" }),
      );
      return Object.freeze(instructions);
    }
    if (operation === loop.updateStore) {
      const update = machineInstruction(
        state.input.profile.cpu,
        register === "x" ? "inx" : register === "y" ? "iny" : "inc",
        register === null ? "storage" : "implied",
        home === null ? null : { kind: "storage", requestId: home.requestId },
        [],
        operation.span,
      );
      if (register !== null) selected.ownWrites.add(update);
      return Object.freeze([update]);
    }
    return Object.freeze([]);
  }
  return lowerFixedCounterRead(operation, state, index);
}

/** Start a fresh occurrence without carrying stale temporary values or address facts from its predecessor. */
export function enterFixedLoopBlock(block: SemanticBlock, state: FunctionLoweringState): void {
  const runtime = state.fixedLoops;
  const occurrence = runtime?.occurrences.get(block.id);
  if (runtime !== undefined) runtime.current = occurrence;
  state.currentSemanticBlockId = occurrence?.source.id ?? block.id;
  if (occurrence?.loop == null) return;
  for (const value of runtime?.expanded.get(occurrence.loop) ?? []) {
    state.values.delete(value);
    state.loadOrigins.delete(value);
  }
  state.aggregateAddressCache = null;
}

/**
 * Replace only expanded-counter reads and admitted pure constant forms in that occurrence.
 * Everything else still traverses the complete ordinary dispatcher, including
 * runtime shifts, bounds guards, calls, staging and helper discovery.
 * @param operation Exact unchanged source operation being emitted now.
 * @param state Current occurrence and original source-value/lifetime identities.
 * @returns True only when the operation is code-free and its value has been installed.
 */
export function selectFixedLoopOperation(
  operation: SemanticOperation,
  state: FunctionLoweringState,
): boolean {
  if (state.fixedLoops?.omitted.has(operation)) return true;
  const occurrence = state.fixedLoops?.current;
  if (occurrence?.loop == null || occurrence.iteration === null) return false;
  const loop = occurrence.loop;
  if (
    !("result" in operation) ||
    operation.result === null ||
    !state.fixedLoops?.ordinalValues.get(loop)?.has(operation.result)
  )
    return false;
  const value =
    operation.kind === "load" &&
    operation.place.path.length === 0 &&
    bindingIdentityKey(operation.place.root) === bindingIdentityKey(loop.counter)
      ? Object.freeze({
          kind: "constant" as const,
          value: occurrence.iteration,
          bytes: typeBytes(operation.type),
          signed: isSignedType(operation.type),
        })
      : foldFixedLoopOrdinal(operation, state.values);
  if (value === null) return false;
  state.values.set(operation.result, value);
  return true;
}

/** Retain occurrence provenance on every block produced by the full dispatcher, including split continuations. */
export function finishFixedLoopBlock(
  blocks: MachineBlock[],
  start: number,
  state: FunctionLoweringState,
): void {
  const runtime = state.fixedLoops;
  const occurrence = runtime?.current;
  if (runtime !== undefined && occurrence !== undefined)
    runtime.sourceBlocks.set(
      occurrence.source,
      Object.freeze([
        ...(runtime.sourceBlocks.get(occurrence.source) ?? []),
        ...blocks.slice(start).map((block) => block.label),
      ]),
    );
  if (runtime === undefined || occurrence?.loop == null || occurrence.iteration === null) return;
  const labels: string[] = [];
  for (let index = start; index < blocks.length; index += 1) {
    const block = blocks[index]!;
    labels.push(block.label);
    blocks[index] = Object.freeze({
      ...block,
      instructions: Object.freeze(
        block.instructions.map((instruction) =>
          Object.freeze({ ...instruction, sourceIteration: occurrence.iteration! }),
        ),
      ),
    });
  }
  const emitted = runtime.emitted.get(occurrence.loop) ?? [];
  emitted.push(Object.freeze({ iteration: occurrence.iteration, blocks: Object.freeze(labels) }));
  runtime.emitted.set(occurrence.loop, emitted);
}

/** Attach conditional loop records without discharging old-home, read or asynchronous A/P obligations. */
export function finishFixedLoops(fn: MachineFunction, runtime: FixedLoopRuntime): MachineFunction {
  if (runtime.observerEvidence)
    fn = Object.freeze({
      ...fn,
      observerBlocks: Object.freeze(
        [...runtime.sourceBlocks].map(([source, labels]) =>
          Object.freeze([source, labels] as const),
        ),
      ),
    });
  if (runtime.policy === undefined || (runtime.expanded.size === 0 && runtime.counters.size === 0))
    return fn;
  for (const [value] of runtime.indexViews)
    if (!runtime.consumedIndices.has(value))
      throw loweringFailure(
        "Held counter index was not consumed by its proved native access",
        runtime.counterFacts[0]?.comparison.span ?? null,
      );
  const actualBlocks = new Map(fn.blocks.map((block) => [block.label, block]));
  for (const counter of runtime.counters.values()) {
    const register = counter.register;
    if (register === null) continue;
    for (const source of counter.loop.function.blocks) {
      if (
        !counter.loop.members.has(source.id) &&
        source !== counter.loop.header &&
        source !== counter.loop.preheader
      )
        continue;
      let live = source !== counter.loop.preheader;
      for (const label of runtime.sourceBlocks.get(source) ?? [])
        for (const instruction of actualBlocks.get(label)?.instructions ?? []) {
          if (counter.ownWrites.has(instruction)) {
            live = true;
            continue;
          }
          if (live && instruction.defines.registers.includes(register))
            throw loweringFailure(
              "Fixed counter register was clobbered by unproved selected code",
              instruction.source,
            );
        }
    }
  }
  const selected = selectFixedCounterHeaderState(fn, runtime);
  if (selected === null)
    throw loweringFailure(
      "Fixed counter lost its complete comparison state",
      runtime.counterFacts[0]?.comparison.span ?? null,
    );
  const byLabel = new Map(selected.blocks.map((block) => [block.label, block]));
  const safeEntry = byteContinuationQuery(byLabel);
  const entries = new Map<string, string>();
  for (const counter of runtime.counters.values()) {
    const { loop, register } = counter;
    const entry = byLabel.get(loop.preheader.id);
    const header = byLabel.get(loop.header.id);
    const compare = header?.instructions[0];
    const incoming = runtime.predecessors.get(loop.header.id) ?? [];
    if (
      register === null ||
      loop.tripDomain.minimum <= 0 ||
      loop.members.size !== 2 ||
      loop.body.terminator.kind !== "jump" ||
      loop.body.terminator.target !== loop.update.id ||
      entry?.terminator.kind !== "jump" ||
      entry.terminator.target !== loop.header.id ||
      header?.instructions.length !== 1 ||
      compare?.opcode !== (register === "x" ? "cpx" : "cpy") ||
      compare.mode !== "immediate" ||
      compare.operand?.kind !== "immediate" ||
      compare.operand.value !== loop.bound ||
      header.terminator.kind !== "branch" ||
      header.terminator.opcode !== "bcc" ||
      header.terminator.target !== loop.body.id ||
      header.terminator.fallthrough !== loop.exit.id ||
      incoming.length !== 2 ||
      !incoming.includes(loop.preheader.id) ||
      !incoming.includes(loop.update.id)
    )
      continue;
    // A straight-line body/update reaches its own unchanged backedge comparison.
    // No other entry elision can supply the overwrite used by this proof.
    if (
      safeEntry(
        loop.body.id,
        0,
        BYTE_WINDOW_CHANGED.n | BYTE_WINDOW_CHANGED.z | BYTE_WINDOW_CHANGED.c,
      )
    )
      entries.set(loop.preheader.id, loop.body.id);
  }
  const proofs: FixedLoopProof[] = [...runtime.expanded].map(([loop]) =>
    Object.freeze({
      loop,
      context: fn.id,
      policy: runtime.policy!,
      representation: "flat-eight",
      changedState: Object.freeze(["a", "x", "y", "n", "z", "c", "v"] as const),
      occurrences: Object.freeze(runtime.emitted.get(loop) ?? []),
      pendingObservers: true,
    }),
  );
  const counters: FixedCounterProof[] = [...runtime.counters.values()].map((counter) =>
    Object.freeze({
      loop: counter.loop,
      context: fn.id,
      representation: counter.register ?? "low-byte",
      originalRequestId: counter.originalRequestId,
      requestId: counter.home?.requestId ?? null,
      firstTestElided: entries.has(counter.loop.preheader.id),
      ...(runtime.observerEvidence
        ? {
            indexUses: Object.freeze(
              [...runtime.indexViews].flatMap(([value, view]) =>
                view.counter === counter ? [Object.freeze({ value, consumer: view.consumer })] : [],
              ),
            ),
          }
        : {}),
      reads: Object.freeze(
        [...counter.reads].map(([value, stagingRequestId]) =>
          Object.freeze({ value, stagingRequestId }),
        ),
      ),
      changedState: Object.freeze(["a", "x", "y", "n", "z", "c", "v"] as const),
      pendingObservers: true,
    }),
  );
  return Object.freeze({
    ...selected,
    blocks: Object.freeze(
      selected.blocks.map((block) => {
        const target = entries.get(block.label);
        return target === undefined || block.terminator.kind !== "jump"
          ? block
          : Object.freeze({ ...block, terminator: Object.freeze({ ...block.terminator, target }) });
      }),
    ),
    ...(proofs.length ? { fixedLoopProofs: Object.freeze(proofs) } : {}),
    ...(counters.length ? { fixedCounterProofs: Object.freeze(counters) } : {}),
  });
}
